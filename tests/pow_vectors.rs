#[test]
fn test_every_spec_vector_bit_for_bit() {
    assert_eq!(VECTORS.len(), 122);
    for &(row, x, y, want) in VECTORS {
        let got = ls_pow(f64::from_bits(x), f64::from_bits(y)).to_bits();
        assert_eq!(got, want, "row {row}: got {got:016x}, want {want:016x}");
    }
}

#[test]
fn test_close_to_the_platform_pow() {
    // Not the oracle (the vectors are), but a gross error would show here.
    let mut s = 0x2545_F491_4F6C_DD1Du64;
    for _ in 0..50_000 {
        s ^= s << 13;
        s ^= s >> 7;
        s ^= s << 17;
        let x = (s >> 11) as f64 / (1u64 << 53) as f64 * 64.0;
        let y = ((s & 0xFFFF) as f64 - 32_768.0) / 256.0;
        let (a, b) = (ls_pow(x, y), x.powf(y));
        if a.is_finite() && b.is_finite() && a != 0.0 {
            let ulps = (a.to_bits() as i64 - b.to_bits() as i64).abs();
            assert!(ulps <= 1, "{x} ** {y}: {a} vs {b}");
        }
    }
}

#[cfg(feature = "interp")]
#[test]
fn test_interpreter_pow_is_ls_pow_at_both_widths() {
    use ir_lang::interp::eval_binary;
    use ir_lang::{BinaryOp, Policy, Type};
    for &(row, x, y, want) in VECTORS {
        let got = eval_binary(BinaryOp::Pow, Policy::NONE, Type::F64, x, y);
        assert_eq!(got, Ok(want), "row {row}");
        // f32: widen, compute, round once.
        let (xf, yf) = (f64::from_bits(x) as f32, f64::from_bits(y) as f32);
        let want32 = (ls_pow(f64::from(xf), f64::from(yf)) as f32).to_bits();
        let got32 = eval_binary(
            BinaryOp::Pow,
            Policy::NONE,
            Type::F32,
            u64::from(xf.to_bits()),
            u64::from(yf.to_bits()),
        );
        assert_eq!(got32, Ok(u64::from(want32)), "row {row} at f32");
    }
}
